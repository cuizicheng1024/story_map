from storymap.script.agent import generation_service

def test_validate_data_quality_skips_generic_places_without_coords():
    md = """# 黄仁宇 生平传记与足迹

## 三、人生历程与重要地点（按时间顺序）

### 📍 重要地点：中国（抗战大后方及战场）
- **公元纪年**：1938—1945年
- **停留时间**：约7年
- **位置**：抗战时期的中国
- **事迹**：抗战期间服役。
- **意义**：军旅经历深刻影响其观察。

### 📍 重要地点：美国
- **公元纪年**：1946年
- **停留时间**：短期进修
- **位置**：美国
- **事迹**：赴美国进修。
- **意义**：后续治学阶段的起点。

## 四、生平时间线

| 年份 | 古称 | 现称 | 事件 |
| --- | --- | --- | --- |
| 1938 | 中国 | 中国 | 抗战期间服役 |
| 1946 | 美国 | 美国 | 赴美国进修 |

## 地点坐标（自动地理编码）
| 现称 | 现代搜索地名 | 纬度 | 经度 | 坐标系 |
| --- | --- | --- | --- | --- |
| 美国 | 美国 | 31.000000 | -100.000000 | WGS84 |
"""

    issues = generation_service.validate_data_quality(md)

    assert "地点坐标缺失：中国" not in issues
