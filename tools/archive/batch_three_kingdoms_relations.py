import sqlite3
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DB_PATH = PROJECT_ROOT / "data" / "people_knowledge.db"
ORIGIN = "manual"


def connect():
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def upsert_relation(conn, source, target, relationship, weight, evidence):
    """插入或更新关系（确保 source <= target 以保持一致性）"""
    if source > target:
        source, target = target, source
    conn.execute(
        """
        INSERT INTO relationships (source_person, target_person, origin, relationship, weight, confidence, evidence)
        VALUES (?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(source_person, target_person) DO UPDATE SET
            origin = excluded.origin,
            relationship = excluded.relationship,
            weight = excluded.weight,
            confidence = excluded.confidence,
            evidence = excluded.evidence,
            updated_at = datetime('now')
        """,
        (source, target, ORIGIN, relationship, weight, 0.95, evidence),
    )


def remove_relation(conn, source, target):
    """删除指定关系"""
    if source > target:
        source, target = target, source
    conn.execute(
        "DELETE FROM relationships WHERE source_person = ? AND target_person = ?",
        (source, target),
    )


