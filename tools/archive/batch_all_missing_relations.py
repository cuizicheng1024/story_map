ORIGIN = "manual"


def get_all_people() -> dict:
    with open(SUMMARY_PATH, encoding="utf-8") as f:
        psi = json.load(f)
    return psi.get("items", {})


def get_people_with_relations() -> set:
    conn = sqlite3.connect(str(DB_PATH))
    rows = conn.execute("SELECT source_person, target_person FROM relationships").fetchall()
    conn.close()
    people = set()
    for s, t in rows:
        people.add(s)
        people.add(t)
    return people


def upsert_relation(conn, a, b, rel, weight, evidence):
    if a > b:
        a, b = b, a
    conn.execute(
        """INSERT INTO relationships (source_person, target_person, origin, relationship, weight, confidence, evidence)
           VALUES (?, ?, ?, ?, ?, ?, ?)
           ON CONFLICT(source_person, target_person) DO UPDATE SET
               origin = excluded.origin,
               relationship = excluded.relationship,
               weight = excluded.weight,
               confidence = excluded.confidence,
               evidence = excluded.evidence,
               updated_at = datetime('now')""",
        (a, b, ORIGIN, rel, weight, 0.9, evidence),
    )


